import 'package:flutter/foundation.dart';

@immutable
class IndentTimelineModel {
  final String action;
  final String title;
  final String description;
  final String actorName;
  final DateTime timestamp;

  const IndentTimelineModel({
    required this.action,
    required this.title,
    required this.description,
    required this.actorName,
    required this.timestamp,
  });

  factory IndentTimelineModel.fromJson(Map<String, dynamic> json) {
    DateTime parseDate(dynamic v) {
      if (v is DateTime) return v;
      if (v is String) return DateTime.tryParse(v) ?? DateTime.now();
      if (v is int) {
        return v > 1000000000000
            ? DateTime.fromMillisecondsSinceEpoch(v)
            : DateTime.fromMillisecondsSinceEpoch(v * 1000);
      }
      return DateTime.now();
    }

    return IndentTimelineModel(
      action: (json['action'] ?? '').toString(),
      title: (json['title'] ?? '').toString(),
      description: (json['description'] ?? '').toString(),
      actorName: (json['actorName'] ?? '').toString(),
      timestamp: parseDate(json['timestamp']),
    );
  }

  Map<String, dynamic> toJson() => {
        'action': action,
        'title': title,
        'description': description,
        'actorName': actorName,
        'timestamp': timestamp.toIso8601String(),
      };
}

typedef IndentRaiseModel = StockRefillRequestModel;

@immutable
class StockRefillRequestModel {
  final String id;
  final String indentNumber;
  final String? groupIndentNumber;
  final String itemId;
  final String itemDescription;
  final String itemCode;
  final String unitOfMeasure;
  final num currentAvailableQty;
  final num currentTotalQty;
  final num balanceQty;
  final num indentQty;
  final String reason;
  final String status; // 'PENDING' | 'APPROVED' | 'REJECTED'
  final String requestedBy;
  final String requesterId;
  final String? reviewedBy;
  final String? reviewedById;
  final DateTime? reviewedAt;
  final String? reviewRemarks;
  final String? make;
  final String? techSpec;
  final String? hsnCode;
  final String? lineNumber;
  final num? preReqQty;
  final num? preqQty;
  final String? documentCategory;
  final String? company;
  final String? costCenter;
  final String? documentDate;
  final String? documentType;
  final DateTime? createdOn;
  final DateTime? lastChangedOn;
  final DateTime? createdAt;
  final DateTime? updatedAt;
  final bool stockCredited;
  final DateTime? stockCreditedAt;
  final String? creditedRackId;
  final String? creditedRackCode;
  final num? creditedQty;
  final String? receiveDocId;
  final String? indentType;
  final String? sourceIssueId;
  final List<IndentTimelineModel> timeline;

  const StockRefillRequestModel({
    required this.id,
    String? indentNumber,
    String? requestNo,
    this.groupIndentNumber,
    required this.itemId,
    String? itemDescription,
    String? itemName,
    required this.itemCode,
    String? unitOfMeasure,
    String? unit,
    required this.currentAvailableQty,
    required this.currentTotalQty,
    num? balanceQty,
    num? indentQty,
    num? requestedQty,
    required this.reason,
    required this.status,
    required this.requestedBy,
    required this.requesterId,
    this.reviewedBy,
    this.reviewedById,
    this.reviewedAt,
    this.reviewRemarks,
    this.make,
    this.techSpec,
    this.hsnCode,
    this.lineNumber,
    this.preReqQty,
    this.preqQty,
    this.documentCategory,
    this.company,
    this.costCenter,
    this.documentDate,
    this.documentType,
    this.createdOn,
    this.lastChangedOn,
    this.createdAt,
    this.updatedAt,
    this.stockCredited = false,
    this.stockCreditedAt,
    this.creditedRackId,
    this.creditedRackCode,
    this.creditedQty,
    this.receiveDocId,
    this.indentType,
    this.sourceIssueId,
    this.timeline = const [],
  })  : indentNumber = indentNumber ?? requestNo ?? '',
        itemDescription = itemDescription ?? itemName ?? '',
        unitOfMeasure = unitOfMeasure ?? unit ?? '',
        indentQty = indentQty ?? requestedQty ?? 0,
        balanceQty = balanceQty ?? currentAvailableQty;

  // Legacy compatibility getters
  String get requestNo => indentNumber;
  num get requestedQty => indentQty;
  String get itemName => itemDescription;
  String get unit => unitOfMeasure;

  bool get isPending => status.toUpperCase() == 'PENDING';
  bool get isApproved => status.toUpperCase() == 'APPROVED';
  bool get isRejected => status.toUpperCase() == 'REJECTED';

  /// True if generated by the automated low-stock threshold trigger
  bool get isAutoRefill =>
      indentType == 'AUTO_REFILL' ||
      requestedBy.toUpperCase().contains('AUTO REFILL') ||
      requestedBy.toUpperCase().contains('SYSTEM') ||
      reason.toUpperCase().startsWith('AUTO REFILL');

  /// True if generated to fulfill a worker's issue demand shortage
  bool get isIssueShortage =>
      indentType == 'ISSUE_SHORTAGE' ||
      reason.toUpperCase().contains('SHORTAGE') ||
      (sourceIssueId != null && sourceIssueId!.isNotEmpty);

  /// True if generated for general warehouse inventory replenishment
  bool get isStoreRefill =>
      indentType == 'STORE_REFILL' || (!isAutoRefill && !isIssueShortage);

  /// True if submitted by a human user requisition
  bool get isRequesterIndent => !isAutoRefill;

  /// True if part of a combined multi-item indent requisition
  bool get isGrouped =>
      groupIndentNumber != null &&
      groupIndentNumber!.isNotEmpty &&
      groupIndentNumber != indentNumber;

  factory StockRefillRequestModel.fromJson(Map<String, dynamic> json) {
    DateTime? parseDate(dynamic v) {
      if (v == null) return null;
      if (v is DateTime) return v;
      if (v is String) return DateTime.tryParse(v);
      if (v is int) {
        return v > 1000000000000
            ? DateTime.fromMillisecondsSinceEpoch(v)
            : DateTime.fromMillisecondsSinceEpoch(v * 1000);
      }
      return null;
    }

    final rawIndentNum =
        (json['indentNumber'] ?? json['requestNo'] ?? '').toString();
    final rawItemDesc =
        (json['itemDescription'] ?? json['itemName'] ?? '').toString();
    final rawUnit = (json['unitOfMeasure'] ?? json['unit'] ?? '').toString();
    final rawIndentQty =
        (json['indentQty'] as num?) ?? (json['requestedQty'] as num?) ?? 0;
    final availQty = (json['currentAvailableQty'] as num?) ?? 0;
    final balQty = (json['balanceQty'] as num?) ?? availQty;

    return StockRefillRequestModel(
      id: (json['_id'] ?? json['id'] ?? '').toString(),
      indentNumber: rawIndentNum,
      groupIndentNumber: json['groupIndentNumber']?.toString(),
      itemId: (json['itemId'] ?? '').toString(),
      itemDescription: rawItemDesc,
      itemCode: (json['itemCode'] ?? '').toString(),
      unitOfMeasure: rawUnit,
      currentAvailableQty: availQty,
      currentTotalQty: (json['currentTotalQty'] as num?) ?? 0,
      balanceQty: balQty,
      indentQty: rawIndentQty,
      reason: (json['reason'] ?? '').toString(),
      status: (json['status'] ?? 'PENDING').toString().toUpperCase(),
      requestedBy: (json['requestedBy'] ?? '').toString(),
      requesterId: (json['requesterId'] ?? '').toString(),
      reviewedBy: json['reviewedBy']?.toString(),
      reviewedById: json['reviewedById']?.toString(),
      reviewedAt: parseDate(json['reviewedAt']),
      reviewRemarks: json['reviewRemarks']?.toString(),
      make: json['make']?.toString(),
      techSpec: json['techSpec']?.toString(),
      hsnCode: json['hsnCode']?.toString(),
      lineNumber: json['lineNumber']?.toString(),
      preReqQty: json['preReqQty'] as num?,
      preqQty: json['preqQty'] as num?,
      documentCategory: json['documentCategory']?.toString(),
      company: json['company']?.toString(),
      costCenter: json['costCenter']?.toString(),
      documentDate: json['documentDate']?.toString(),
      documentType: json['documentType']?.toString(),
      createdOn: parseDate(json['createdOn']),
      lastChangedOn: parseDate(json['lastChangedOn']),
      createdAt: parseDate(json['createdAt']),
      updatedAt: parseDate(json['updatedAt']),
      stockCredited: json['stockCredited'] == true,
      stockCreditedAt: parseDate(json['stockCreditedAt']),
      creditedRackId: json['creditedRackId']?.toString(),
      creditedRackCode: json['creditedRackCode']?.toString(),
      creditedQty: json['creditedQty'] as num?,
      receiveDocId: json['receiveDocId']?.toString(),
      indentType: json['indentType']?.toString(),
      sourceIssueId: json['sourceIssueId']?.toString(),
      timeline: (json['timeline'] is List)
          ? (json['timeline'] as List)
              .map((e) => e is Map<String, dynamic>
                  ? IndentTimelineModel.fromJson(e)
                  : IndentTimelineModel.fromJson(Map<String, dynamic>.from(e as Map)))
              .toList()
          : const [],
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'indentNumber': indentNumber,
      'groupIndentNumber': groupIndentNumber,
      'requestNo': requestNo,
      'itemId': itemId,
      'itemDescription': itemDescription,
      'itemName': itemName,
      'itemCode': itemCode,
      'unitOfMeasure': unitOfMeasure,
      'unit': unit,
      'currentAvailableQty': currentAvailableQty,
      'currentTotalQty': currentTotalQty,
      'balanceQty': balanceQty,
      'indentQty': indentQty,
      'requestedQty': requestedQty,
      'reason': reason,
      'status': status,
      'requestedBy': requestedBy,
      'requesterId': requesterId,
      'reviewedBy': reviewedBy,
      'reviewedById': reviewedById,
      'reviewedAt': reviewedAt?.toIso8601String(),
      'reviewRemarks': reviewRemarks,
      'make': make,
      'techSpec': techSpec,
      'hsnCode': hsnCode,
      'lineNumber': lineNumber,
      'preReqQty': preReqQty,
      'preqQty': preqQty,
      'documentCategory': documentCategory,
      'company': company,
      'costCenter': costCenter,
      'documentDate': documentDate,
      'indentType': indentType,
      'sourceIssueId': sourceIssueId,
      'documentType': documentType,
      'createdOn': createdOn?.toIso8601String(),
      'lastChangedOn': lastChangedOn?.toIso8601String(),
      'createdAt': createdAt?.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      'stockCredited': stockCredited,
      'stockCreditedAt': stockCreditedAt?.toIso8601String(),
      'creditedRackId': creditedRackId,
      'creditedRackCode': creditedRackCode,
      'creditedQty': creditedQty,
      'receiveDocId': receiveDocId,
      'timeline': timeline.map((e) => e.toJson()).toList(),
    };
  }
}
